create table dining_halls(
    id bigint generated by default as identity primary key,
    name text not null unique
);

create table menu_items(
    id bigint generated by default as identity primary key,
    name text not null
);

create table ingredients(
    id bigint generated by default as identity primary key,
    name text not null unique
);

create table allergens(
    id bigint generated by default as identity primary key,
    name text not null unique
);

create table menu_item_ingredients(
    menu_item_id bigint not null references menu_items(id) on delete cascade,
    ingredient_id bigint not null references ingredients(id) on delete cascade,
    primary key (menu_item_id, ingredient_id)
);

create table menu_item_allergens(
    menu_item_id bigint not null references menu_items(id) on delete cascade,
    allergen_id bigint not null references allergens(id) on delete cascade,
    primary key (menu_item_id, allergen_id)
);

create table meals(
    id bigint generated by default as identity primary key,
    dining_hall_id bigint not null references dining_halls(id),
    date date not null,
    meal_type text not null,
    unique (dining_hall_id, date, meal_type)

);

create table meal_items(
    meal_id bigint not null references meals(id) on delete cascade,
    menu_item_id bigint not null references menu_items(id) on delete cascade,
    primary key (meal_id, menu_item_id)
);

